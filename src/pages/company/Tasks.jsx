import React, { useEffect, useState } from "react";
import { useParams, useOutletContext, useSearchParams } from "react-router-dom";
import { base44 } from "@/api/base44Client";
import { CheckSquare, Plus, X } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import PageHeader from "@/components/PageHeader";
import EmptyState from "@/components/EmptyState";
import TaskCard from "@/components/tasks/TaskCard";
import DocumentDetailDialog from "@/components/documents/DocumentDetailDialog";
import AdvisorWorkDialog, { isAdvisorWork } from "@/components/documents/AdvisorWorkDialog";
import { useTaskRuns } from "@/lib/taskRuns";
import { toast } from "@/components/ui/use-toast";

const COLUMNS = [
  { key: "todo", label: "To Do" },
  { key: "in_progress", label: "In Progress" },
  { key: "review", label: "Review" },
  { key: "done", label: "Done" },
];

export default function Tasks() {
  const { companyId } = useParams();
  const { company } = useOutletContext();
  const [searchParams, setSearchParams] = useSearchParams();
  const meetingFilter = searchParams.get("meeting");
  const [items, setItems] = useState(null);
  const [advisors, setAdvisors] = useState([]);
  const [advisorsLoaded, setAdvisorsLoaded] = useState(false);
  const [projects, setProjects] = useState([]);
  const [open, setOpen] = useState(false);
  const [acknowledgingId, setAcknowledgingId] = useState(null);
  const [viewDoc, setViewDoc] = useState(null);
  // A "Do this for me" result opens in its own clean view, not the old
  // deliverable viewer.
  const [workDoc, setWorkDoc] = useState(null);
  const EMPTY_FORM = { title: "", assigned_to: "", project_id: "", task_type: "", brief: "" };
  const [form, setForm] = useState(EMPTY_FORM);

  const load = () => base44.entities.Task.filter({ company_id: companyId }, "-created_date", 200).then(setItems);
  useEffect(() => { load(); base44.entities.Advisor.filter({ company_id: companyId }, "-created_date", 100).then((a) => { setAdvisors(a); setAdvisorsLoaded(true); }); base44.entities.Project.filter({ company_id: companyId }, "-created_date", 100).then(setProjects); }, [companyId]);

  // A hand-made task can be one an advisor does for you (Draft or Plan, so
  // "Do this for me" works on it), which needs one of your AI advisors.
  const assignee = advisors.find((a) => a.name === form.assigned_to);
  const aiAssignee = assignee && assignee.type !== "human" ? assignee : null;
  const needsAdvisor = !!form.task_type && !aiAssignee;
  const create = async () => {
    if (!form.title.trim() || needsAdvisor) return;
    await base44.entities.Task.create({
      company_id: companyId, title: form.title, assigned_to: form.assigned_to, project_id: form.project_id || undefined,
      advisor_id: aiAssignee?.id || null, task_type: form.task_type || null, description: form.brief.trim() || null,
      created_by: "Founder", status: "todo",
    });
    setForm(EMPTY_FORM); setOpen(false); load();
  };

  // A task with source_meeting_id is a real commitment from a board
  // resolution's next-24-hours actions (runChairSynthesis). Only those get an
  // advisor acknowledgment; ad-hoc tasks completing is not a board moment.
  const acknowledgeCompletion = async (task) => {
    if (!task.source_meeting_id) return;
    setAcknowledgingId(task.id);
    try {
      const res = await base44.functions.invoke("acknowledgeTaskCompletion", { task_id: task.id });
      if (res.data?.advisor_acknowledgment) {
        setItems((prev) => prev?.map((t) => (t.id === task.id ? { ...t, ...res.data } : t)) || prev);
      }
    } catch {
      // Silent — a missing acknowledgment is a lesser loss than blocking completion on it.
    } finally {
      setAcknowledgingId(null);
    }
  };

  const markDone = async (task) => {
    await base44.entities.Task.update(task.id, { status: "done" });
    load();
    acknowledgeCompletion(task);
  };

  const move = async (task, dir) => {
    const idx = COLUMNS.findIndex((c) => c.key === task.status);
    const next = dir === "forward" ? COLUMNS[idx + 1]?.key : COLUMNS[idx - 1]?.key;
    if (!next) return;
    if (next === "done") { await markDone(task); return; }
    await base44.entities.Task.update(task.id, { status: next }); load();
  };

  const completeForFounder = async (task) => {
    await markDone(task);
  };

  const visibleItems = meetingFilter ? (items || []).filter((t) => t.source_meeting_id === meetingFilter) : items;
  // "Do this for me": each task's latest run; a finished run moves its task,
  // so the board reloads when one settles.
  const { runs, put } = useTaskRuns((visibleItems || []).map((t) => t.id), load);

  return (
    <div>
      <PageHeader eyebrow="Owned work" title="Tasks" description="Assigned by you or generated by your advisors from the boardroom.">
        <Button onClick={() => setOpen(true)} variant="primary" className="px-5"><Plus className="w-4 h-4 mr-1.5" /> New task</Button>
      </PageHeader>
      {meetingFilter && (
        <div className="flex items-center justify-between gap-3 bg-accent/50 rounded-xl px-4 py-2.5 mb-5 text-sm">
          <span>Showing the {visibleItems?.length ?? ""} task{visibleItems?.length === 1 ? "" : "s"} from that board meeting.</span>
          <button onClick={() => setSearchParams({})} className="flex items-center gap-1 text-muted-foreground hover:text-foreground transition-colors shrink-0">
            <X className="w-3.5 h-3.5" /> Show all tasks
          </button>
        </div>
      )}
      {items === null ? <div className="h-40 rounded-2xl bg-secondary/60 animate-pulse" />
        : visibleItems.length === 0 ? <EmptyState icon={CheckSquare} title={meetingFilter ? "No tasks from that meeting" : "No tasks yet"} description={meetingFilter ? "They may have already been completed or removed." : "Create a task, or let your board assign work during a meeting."} action={!meetingFilter && <Button onClick={() => setOpen(true)} variant="primary" className="px-6"><Plus className="w-4 h-4 mr-1.5" /> New task</Button>} />
        : (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
          {COLUMNS.map((col) => {
            const colItems = visibleItems.filter((t) => t.status === col.key);
            return (
              <div key={col.key} className="bg-secondary/40 rounded-2xl p-3">
                <div className="flex items-center justify-between px-2 mb-3">
                  <span className="text-sm font-medium">{col.label}</span>
                  <span className="text-xs text-muted-foreground">{colItems.length}</span>
                </div>
                <div className="space-y-2 min-h-[40px]">
                  {colItems.map((t) => (
                    <TaskCard
                      key={t.id}
                      task={t}
                      advisors={advisors}
                      run={runs[t.id]}
                      onRunChanged={(run) => { if (run) put(run); load(); }}
                      acknowledging={acknowledgingId === t.id}
                      onCompleteFounder={completeForFounder}
                      onMove={move}
                      onOpenDocument={async (docId) => {
                        const d = await base44.entities.Document.get(docId).catch(() => null);
                        if (!d) { toast({ title: "That result isn't there any more", description: "It may have been deleted from Knowledge." }); return; }
                        if (isAdvisorWork(d)) { setViewDoc(null); setWorkDoc(d); } else { setWorkDoc(null); setViewDoc(d); }
                      }}
                      canBack={COLUMNS.findIndex((c) => c.key === col.key) > 0}
                      canForward={COLUMNS.findIndex((c) => c.key === col.key) < COLUMNS.length - 1}
                    />
                  ))}
                </div>
              </div>
            );
          })}
        </div>
      )}

      <Dialog open={open} onOpenChange={(o) => { setOpen(o); if (!o) setForm(EMPTY_FORM); }}>
        <DialogContent className="sm:max-w-md">
          <DialogHeader><DialogTitle className="font-display text-2xl font-light">New task</DialogTitle></DialogHeader>
          <div className="space-y-4 pt-2">
            <div><Label htmlFor="task-title" className="mb-1.5 block">Task</Label><Input id="task-title" value={form.title} onChange={(e)=>setForm(f=>({...f,title:e.target.value}))} autoFocus /></div>
            <div><Label htmlFor="task-kind" className="mb-1.5 block">What kind of task</Label>
              <select id="task-kind" value={form.task_type} onChange={(e)=>setForm(f=>({...f,task_type:e.target.value}))} className="w-full h-10 rounded-md border border-input bg-background px-3 text-sm">
                <option value="">A to-do you do yourself</option>
                <option value="draft">Draft: an advisor writes it for you to send</option>
                <option value="plan">Plan: an advisor writes a dated checklist</option>
              </select>
            </div>
            <div><Label htmlFor="task-assignee" className="mb-1.5 block">{form.task_type ? "Which advisor does it" : "Assign to"}</Label>
              <select id="task-assignee" value={form.assigned_to} onChange={(e)=>setForm(f=>({...f,assigned_to:e.target.value}))} className="w-full h-10 rounded-md border border-input bg-background px-3 text-sm">
                <option value="">{form.task_type ? "Choose an advisor" : "Unassigned"}</option>
                {advisors.filter((a) => !form.task_type || a.type !== "human").map(a=><option key={a.id}>{a.name}</option>)}
              </select>
            </div>
            {form.task_type && (
              <div><Label htmlFor="task-brief" className="mb-1.5 block">What should they know? <span className="font-normal text-muted-foreground">(optional)</span></Label>
                <textarea id="task-brief" value={form.brief} onChange={(e)=>setForm(f=>({...f,brief:e.target.value}))} rows={3} maxLength={1500}
                  placeholder="Who it's for, what it should say, anything they need"
                  className="block w-full rounded-md border border-input bg-background p-3 text-sm outline-none focus-visible:ring-2 focus-visible:ring-ring" />
              </div>
            )}
            <div><Label htmlFor="task-project" className="mb-1.5 block">Project</Label>
              <select id="task-project" value={form.project_id} onChange={(e)=>setForm(f=>({...f,project_id:e.target.value}))} className="w-full h-10 rounded-md border border-input bg-background px-3 text-sm">
                <option value="">None</option>{projects.map(p=><option key={p.id} value={p.id}>{p.name}</option>)}
              </select>
            </div>
            {needsAdvisor && advisorsLoaded && (
              <p className="text-sm text-muted-foreground">
                {advisors.some((a) => a.type !== "human") ? "Choose which advisor does it." : "Draft and Plan need one of your advisors; add one on Your advisors first."}
              </p>
            )}
            <div className="flex justify-end gap-2"><Button variant="ghost" onClick={()=>{ setOpen(false); setForm(EMPTY_FORM); }}>Cancel</Button><Button onClick={create} disabled={!form.title.trim() || needsAdvisor}>Create</Button></div>
          </div>
        </DialogContent>
      </Dialog>

      {workDoc && <AdvisorWorkDialog key={workDoc.id} doc={workDoc} advisors={advisors} onClose={() => setWorkDoc(null)} />}

      {viewDoc && (
        <DocumentDetailDialog
          doc={viewDoc}
          advisors={advisors}
          company={company}
          onClose={() => setViewDoc(null)}
          onRefresh={async () => {
            const d = await base44.entities.Document.get(viewDoc.id);
            setViewDoc(d);
            load();
          }}
        />
      )}
    </div>
  );
}
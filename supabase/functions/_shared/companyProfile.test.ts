import { assert, assertEquals } from 'jsr:@std/assert@1';
import { companyProfile, profileFacts } from './companyProfile.ts';

Deno.test("the founder's filled-in profile is given as stated facts, gaps left out", () => {
  const petit = {
    name: 'petit m', description: "Children's dinner sets. ceramic with silicone cradle.", company_type: "Children's Dinnerware",
    stage: 'idea_validation', country: 'United Kingdom', current_challenges: 'How do I get this up and running',
    target_customer: '', business_model: null, tagline: 'Welcome to this exciting journey',
  };
  // company_type and the tagline are generated by onboarding, not stated.
  assertEquals(profileFacts(petit), [
    "What it is: Children's dinner sets. ceramic with silicone cradle.",
    'Stage: validating the idea', 'Country: United Kingdom', 'Current challenges: How do I get this up and running',
  ]);
  const block = companyProfile(petit);
  assert(block.startsWith("WHAT THE FOUNDER HAS TOLD US about petit m (facts they stated: use them, and don't list them as missing or ask for them again. If one is too vague to act on, or the founder now says otherwise, ask about that specifically):"));
  assert(!block.includes('Dinnerware'));
  assert(block.includes('- What it is: Children') && !block.includes('Welcome to this exciting journey'));
  assertEquals(companyProfile({ name: 'Empty Co' }), 'Company: Empty Co\n');
  assertEquals(companyProfile(null), '');
});
